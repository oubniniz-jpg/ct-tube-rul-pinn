"""
CT-Tube Data Loader
====================
Loads synthetic (or real) CT X-ray tube degradation data and prepares
train/val/test splits identical in structure to CMAPSSLoader.

Input: CSV with columns generated by DegradationEngine.generate_dataset()
Output: dict of DataLoaders + metadata (same interface as CMAPSSLoader)

Feature set (9 measurable sensor channels):
  anode_temperature, oil_temperature, tube_voltage_kv, tube_current_ma,
  filament_current_a, vacuum_pressure_pa, rotor_vibration_rms,
  thermal_stress_pa, ambient_temperature_k
(3 leaky channels - scan_cycle, cumulative_stress_pa, filament_diameter_m -
 were removed; see the FEATURE_COLS note below.)
"""

import numpy as np
import pandas as pd
import torch
from torch.utils.data import Dataset, DataLoader as TorchDataLoader
from sklearn.preprocessing import MinMaxScaler


# NOTE: 3 features removed to eliminate target leakage (see Methodology).
# Removed - unmeasurable on a real tube AND monotonic with age, i.e. they
# encode the RUL answer directly:
#   - scan_cycle           (literally the age index; RUL = lifespan - age)
#   - cumulative_stress_pa (running integral of stress, monotonic with age)
#   - filament_diameter_m  (latent health state, not measurable in a hospital)
# The 9 retained channels are all quantities a real CT scanner can measure.
# (scan_cycle still exists as a COLUMN in the CSV for sorting/RUL - it is
#  simply no longer fed to the model as an input feature.)
FEATURE_COLS = [
    "anode_temperature", "oil_temperature", "tube_voltage_kv", "tube_current_ma",
    "filament_current_a", "vacuum_pressure_pa",
    "rotor_vibration_rms", "thermal_stress_pa", "ambient_temperature_k",
]

RUL_CAP = 50000   # cycles — cap early-life RUL (same idea as C-MAPSS RUL_CAP=125)


class CTDataset(Dataset):
    def __init__(self, X: np.ndarray, y: np.ndarray):
        self.X = torch.FloatTensor(X)
        self.y = torch.FloatTensor(y)

    def __len__(self): return len(self.X)
    def __getitem__(self, idx): return self.X[idx], self.y[idx]


class CTPairDataset(Dataset):
    """Same-tube pairs for PINN monotonicity loss."""
    def __init__(self, per_tube: list, step: int = 5):
        early, late = [], []
        for tube_seqs in per_tube:
            T = len(tube_seqs)
            if T < step + 1:
                continue
            for i in range(T - step):
                early.append(tube_seqs[i])
                late.append(tube_seqs[i + step])
        self.early = torch.FloatTensor(np.array(early))
        self.late  = torch.FloatTensor(np.array(late))

    def __len__(self): return len(self.early)
    def __getitem__(self, idx): return self.early[idx], self.late[idx]


class CTLoader:
    def __init__(self, csv_path: str, seq_len: int = 50,
                 rul_cap: int = RUL_CAP, val_fraction: float = 0.15,
                 test_fraction: float = 0.15, batch_size: int = 32,
                 max_tubes: int = 200, stride: int = 50,
                 train_fraction: float = 1.0):
        self.csv_path      = csv_path
        self.seq_len       = seq_len
        self.rul_cap       = rul_cap
        self.val_fraction  = val_fraction
        self.test_fraction = test_fraction
        self.batch_size    = batch_size
        self.max_tubes     = max_tubes      # limit tubes loaded into RAM
        self.stride        = stride         # step between sequence windows
        self.train_fraction = train_fraction  # 0..1 — fraction of train tubes to use
        self.scaler        = MinMaxScaler()

    def prepare(self) -> dict:
        # ── Step 1: scan only tube_id + scan_cycle to pick valid tubes ──
        print("  Scanning tube IDs (chunked read)...")
        counts = {}
        for chunk in pd.read_csv(self.csv_path,
                                  usecols=["tube_id", "scan_cycle"],
                                  chunksize=500_000):
            for tid, cnt in chunk.groupby("tube_id")["scan_cycle"].count().items():
                counts[tid] = counts.get(tid, 0) + cnt

        valid_ids = [tid for tid, cnt in counts.items() if cnt >= self.seq_len]

        # Limit to max_tubes
        if self.max_tubes and len(valid_ids) > self.max_tubes:
            np.random.seed(42)
            valid_ids = list(np.random.choice(valid_ids, self.max_tubes, replace=False))

        valid_set = set(valid_ids)
        print(f"  Loading {len(valid_ids)} tubes from CSV (chunked)...")

        # ── Step 2: read only the selected tubes ────────────────────────
        chunks = []
        for chunk in pd.read_csv(self.csv_path, chunksize=500_000):
            filtered = chunk[chunk["tube_id"].isin(valid_set)]
            if len(filtered):
                chunks.append(filtered)
        df = pd.concat(chunks, ignore_index=True)

        # Cap and normalise RUL
        df["rul_capped"] = df["rul"].clip(upper=self.rul_cap)

        # Fit scaler on all training features (will re-split below)
        all_ids = df["tube_id"].unique()
        np.random.seed(42)
        np.random.shuffle(all_ids)
        n_test = max(1, int(len(all_ids) * self.test_fraction))
        n_val  = max(1, int(len(all_ids) * self.val_fraction))
        test_ids  = set(all_ids[:n_test])
        val_ids   = set(all_ids[n_test:n_test + n_val])
        full_train_ids = all_ids[n_test + n_val:]

        # Optionally subsample training tubes (data-scarcity experiment)
        if self.train_fraction < 1.0:
            n_keep = max(1, int(len(full_train_ids) * self.train_fraction))
            full_train_ids = full_train_ids[:n_keep]
        train_ids = set(full_train_ids)

        tr_df = df[df["tube_id"].isin(train_ids)]
        va_df = df[df["tube_id"].isin(val_ids)]
        te_df = df[df["tube_id"].isin(test_ids)]

        self.scaler.fit(tr_df[FEATURE_COLS].values)

        def scale(frame):
            out = frame.copy()
            out[FEATURE_COLS] = self.scaler.transform(frame[FEATURE_COLS].values)
            return out

        tr_df = scale(tr_df)
        va_df = scale(va_df)
        te_df = scale(te_df)

        X_tr, y_tr, per_tube = self._build_sequences(tr_df, return_per_tube=True)
        X_va, y_va, _        = self._build_sequences(va_df)
        X_te, y_te, te_per_tube = self._build_sequences(te_df, return_per_tube=True)

        # Normalise RUL to [0,1]
        y_tr = y_tr / self.rul_cap
        y_va = y_va / self.rul_cap
        y_te = y_te / self.rul_cap

        pair_ds = CTPairDataset(per_tube, step=5)

        print(f"  CT-Tube dataset — {len(FEATURE_COLS)} features")
        print(f"  Tubes : {len(train_ids)} train / {len(val_ids)} val / {len(test_ids)} test")
        print(f"  Sequences : {len(X_tr):,} train / {len(X_va):,} val / {len(X_te):,} test")
        print(f"  Same-tube pairs (physics): {len(pair_ds):,}")

        def make_loader(X, y, shuffle):
            return TorchDataLoader(CTDataset(X, y),
                                   batch_size=self.batch_size, shuffle=shuffle)

        return {
            "train":        make_loader(X_tr, y_tr, shuffle=True),
            "val":          make_loader(X_va, y_va, shuffle=False),
            "test":         make_loader(X_te, y_te, shuffle=False),
            "train_pairs":  TorchDataLoader(pair_ds, batch_size=self.batch_size,
                                            shuffle=True, drop_last=True),
            "n_features":   len(FEATURE_COLS),
            "feature_names": FEATURE_COLS,
            "rul_cap":      self.rul_cap,
            "test_per_tube": te_per_tube,   # ordered per-tube windows for monotonicity eval
        }

    def _build_sequences(self, df, return_per_tube=False):
        X_list, y_list, per_tube = [], [], []
        for uid in df["tube_id"].unique():
            tube = df[df["tube_id"] == uid].sort_values("scan_cycle")
            feats = tube[FEATURE_COLS].values
            rul   = tube["rul_capped"].values
            T = len(feats)
            if T < self.seq_len:
                continue
            seqs = []
            # Use stride to reduce number of sequences (saves RAM)
            indices = range(0, T - self.seq_len + 1, self.stride)
            for t in indices:
                X_list.append(feats[t: t + self.seq_len])
                y_list.append(rul[t + self.seq_len - 1])
                seqs.append(feats[t: t + self.seq_len])
            per_tube.append(np.array(seqs, dtype=np.float32))

        X = np.array(X_list, dtype=np.float32)
        y = np.array(y_list, dtype=np.float32)
        return (X, y, per_tube) if return_per_tube else (X, y, None)
