"""
Data loading and preprocessing pipeline for CT-scanner maintenance data.
Handles both real hospital logs and synthetic simulation data.
"""

import numpy as np
import pandas as pd
import torch
from torch.utils.data import Dataset, DataLoader as TorchDataLoader
from sklearn.preprocessing import MinMaxScaler


class RULDataset(Dataset):
    """PyTorch dataset for RUL prediction with sliding window sequences."""

    def __init__(self, sequences: np.ndarray, targets: np.ndarray):
        self.sequences = torch.FloatTensor(sequences)
        self.targets = torch.FloatTensor(targets)

    def __len__(self):
        return len(self.sequences)

    def __getitem__(self, idx):
        return self.sequences[idx], self.targets[idx]


class DataLoader:
    """Loads and prepares data for model training."""

    def __init__(self, config: dict):
        self.config = config
        self.data_config = config["data"]
        self.scaler = MinMaxScaler()
        # 12-channel feature set — superset of all competing literature:
        #   anode_temperature, oil_temperature       (thermal; Zhou 2024 oil = #1 feature)
        #   tube_voltage_kv, tube_current_ma         (electrical; Pomšár 2025)
        #   filament_current_a, filament_diameter_m  (filament; Shamim 2024 + Richardson-Dushman)
        #   vacuum_pressure_pa                       (vacuum / arcing; Tang 2026)
        #   rotor_vibration_rms                      (mechanical; Shamim 2024)
        #   thermal_stress_pa, cumulative_stress_pa  (fatigue; Equation 3)
        #   scan_cycle                               (age proxy)
        #   ambient_temperature_k                    (hospital context; Waid 2023)
        self.feature_columns = [
            "anode_temperature",
            "oil_temperature",
            "tube_voltage_kv",
            "tube_current_ma",
            "filament_current_a",
            "filament_diameter_m",
            "vacuum_pressure_pa",
            "rotor_vibration_rms",
            "thermal_stress_pa",
            "cumulative_stress_pa",
            "scan_cycle",
            "ambient_temperature_k",
        ]

    def load_synthetic_data(self, path: str) -> pd.DataFrame:
        """Load synthetic data generated by the degradation engine."""
        return pd.read_csv(path)

    def create_sequences(self, df: pd.DataFrame, tube_id: int) -> tuple:
        """Create sliding window sequences for a single tube.

        Returns:
            sequences: array of shape (num_windows, seq_length, num_features)
            targets: array of shape (num_windows,) with RUL values
        """
        tube_data = df[df["tube_id"] == tube_id].sort_values("scan_cycle")
        seq_len = self.data_config["sequence_length"]

        features = tube_data[self.feature_columns].values
        rul = tube_data["rul"].values

        sequences, targets = [], []
        for i in range(len(features) - seq_len):
            sequences.append(features[i:i + seq_len])
            targets.append(rul[i + seq_len])

        return np.array(sequences), np.array(targets)

    def prepare_dataset(self, df: pd.DataFrame) -> dict:
        """Prepare full dataset with train/val/test split.

        Returns dict with 'train', 'val', 'test' DataLoaders.
        """
        # Normalize features
        df[self.feature_columns] = self.scaler.fit_transform(df[self.feature_columns])

        # Normalize RUL per tube (0 to 1)
        for tid in df["tube_id"].unique():
            mask = df["tube_id"] == tid
            max_rul = df.loc[mask, "rul"].max()
            if max_rul > 0:
                df.loc[mask, "rul"] = df.loc[mask, "rul"] / max_rul

        # Split by tube_id
        tube_ids = df["tube_id"].unique()
        np.random.shuffle(tube_ids)
        n = len(tube_ids)
        train_end = int(n * self.data_config["train_ratio"])
        val_end = train_end + int(n * self.data_config["val_ratio"])

        splits = {
            "train": tube_ids[:train_end],
            "val": tube_ids[train_end:val_end],
            "test": tube_ids[val_end:],
        }

        dataloaders = {}
        batch_size = self.config["training"]["batch_size"]

        for split_name, ids in splits.items():
            all_seqs, all_targets = [], []
            for tid in ids:
                seqs, tgts = self.create_sequences(df, tid)
                if len(seqs) > 0:
                    all_seqs.append(seqs)
                    all_targets.append(tgts)

            if all_seqs:
                X = np.concatenate(all_seqs)
                y = np.concatenate(all_targets)
                dataset = RULDataset(X, y)
                dataloaders[split_name] = TorchDataLoader(
                    dataset,
                    batch_size=batch_size,
                    shuffle=(split_name == "train"),
                )

        return dataloaders
